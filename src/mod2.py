import math

# Создаем функцию решения квадратного уравнения
def fun2(a, b, c):
    # Проверяем граничный случай a = 0
    if a == 0:
        return "Ошибка: a не может быть 0"
    d = b ** 2 - 4 * a * c
    # Если дискриминант меньше 0
    if d < 0:
        return []
    # Если дискриминант равен 0
    if d == 0:
        return [-b / (2 * a)]
    # Вычисляем два корня
    x1 = (-b + math.sqrt(d)) / (2 * a)
    x2 = (-b - math.sqrt(d)) / (2 * a)
    return [x1, x2]
